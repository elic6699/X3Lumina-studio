#ifndef X3F_COLFPN_H
#define X3F_COLFPN_H

/* Merrill 列 FPN（竖条纹杂讯）标定式校正 —— 显示域版。
 *
 * 来源：/tmp/oe_yellow/proto_colfpn.py 第二轮原型（全局施加 + 精确解卷积，
 * 实测 DP3M0877 天空剖面 max|hp9| 5.4 → 0.40/255）的产品化。
 * 机制与验证见 （§1/§24）。
 *
 * ★ 为什么在显示域而不是 lin 域做（2026-10-27 实测定案）：
 *   0877 上 lin 域标定（中亮平滑行剖面）与显示域天空列纹不对应
 *   （lin→显示链含 3×3 色彩矩阵 + tone，且天空区列纹幅度随亮度区域
 *   变化——暗部另有 0.03 lin 的加性列纹，与亮部不是同一张表）；
 *   原型显示域标定已实测有效。校正在 apply_decode_unsharp 之前施加，
 *   锐化放大的列纹源头一并消除（实测锐化把 0.8/255 的列纹放大 ×5）。
 *
 * 算法（同原型）：
 *   1. 平滑亮行（低水平梯度 30 分位 + 亮度窗 80..240，≤512 行）取
 *      逐列中位数剖面 prof[ch][x]（0..255 口径）；
 *   2. 窄尺度高通 h = prof − box9(prof)（宽缓渐变是真实结构）；
 *   3. 精确解卷积 o = hp9^{-1}(h)：o = h + box9(o) 迭代 8 轮（直接拿 h
 *      当 offset 会欠校正，hp9 算子需自反）；
 *   4. 幅度门限 |o| < 0.35/255 → 0（阈值下是噪声不是 FPN）；
 *   5. 全图逐列全局减（不做空间门控——门控版只覆盖 13% 像素是第一轮
 *      失败根因，§24.1）。
 *
 * 缓存：本图标定成功 → 表进缓存（键 = w×h）；本图无可标定平坦区 →
 * 回落缓存表；无缓存 → 不动作。内部互斥锁保护。
 *
 * 门控：X3F_COLFPN=1 显式开启（默认关 = 不调用 = 逐位零回归）。
 * 可调：X3F_COLFPN_THR（0..255 口径幅度门限，默认 0.35）、
 *       X3F_COLFPN_DEBUG=1 打印标定诊断。
 */

void x3f_colfpn_apply_disp(void *out, int w, int h, int stride, int bits);

#endif /* X3F_COLFPN_H */
